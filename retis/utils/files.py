"""
File management utilities for Retis.

This module provides utility functions responsible for handling
file-related operations throughout the Retis app.

It manages the creation, writing and updating of configuration
script files generated by the application, ensuring that the
output is stored in the appropriate location and format.

The module supports the handling of output files with supported
extensions, such as .txt and .cfg, allowing users to save their
generated Cisco IOS configuration scripts.

It also provides the necessary functionality to maintain the
integrity of the generated files during the configuration
generation workflow.

These utilities are designed to be reusable across different
application components, reducing code duplication and centralizing
file-related operations.

Attributes:
    __author__ (str): Edgar Masague.
    __version__ (str): 0.1.0.
    __project__ (str): Retis.
    __license__ (str): MIT License.
    __maintainer__ (str): Edgar Masague.
    __status__ (str): Development.
"""

from pathlib import Path


class FileManager:
    """Handle saving generated configuration scripts."""

    SUPPORTED_EXTENSIONS = (".cfg", ".txt")

    def __init__(self, output_dir: Path | None = None) -> None:
        """Set the output directory (created lazily on first save)."""
        self.output_dir = output_dir or Path.cwd() / "output"

    def resolve(self, filename: str, extension: str = ".txt") -> Path:
        """
        Return the destination path for a filename.

        Raises:
            ValueError: If the filename or extension is invalid.
        """
        if extension not in self.SUPPORTED_EXTENSIONS:
            raise ValueError("Only .cfg and .txt files are supported.")

        name = Path(filename).name

        if not name:
            raise ValueError("Filename cannot be empty.")

        if Path(name).suffix.lower() not in self.SUPPORTED_EXTENSIONS:
            name += extension

        return self.output_dir / name

    def exists(self, filename: str, extension: str = ".txt") -> bool:
        """Check whether the destination file already exists."""
        return self.resolve(filename, extension).exists()

    def save(
        self,
        content: str,
        filename: str,
        extension: str = ".txt",
    ) -> Path:
        """
        Write a complete script to the output file (overwrites).

        Returns:
            Path to the saved file.

        Raises:
            ValueError: If the filename or extension is invalid.
            OSError: If the file cannot be written.
        """
        path = self.resolve(filename, extension)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(content.rstrip() + "\n", encoding="utf-8")
        return path

    def remove(self, filename: str, extension: str = ".txt") -> None:
        """Delete the output file if it exists."""
        self.resolve(filename, extension).unlink(missing_ok=True)
